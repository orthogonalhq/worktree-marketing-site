import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const blogDirectory = path.join(process.cwd(), "src", "content", "blog");
const registryPath = path.join(blogDirectory, "registry.ts");

const entries = (await readdir(blogDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".mdx"))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, "en"));

if (entries.length === 0) {
  throw new Error(`No blog MDX files found in ${blogDirectory}.`);
}

const imports = entries
  .map(
    (filename, index) =>
      `import Article${index}, { metadata as article${index}Metadata } from "./${filename}";`,
  )
  .join("\n");

const articles = entries
  .map(
    (_, index) => `  {
    metadata: article${index}Metadata,
    Component: Article${index},
  },`,
  )
  .join("\n");

const registry = `// Generated by scripts/generate-blog-registry.mjs. Do not edit manually.
import type { ComponentType } from "react";

import type { ArticleMetadata } from "@/lib/blog/schema";
${imports}

export type RegisteredArticle = {
  metadata: ArticleMetadata;
  Component: ComponentType;
};

export const articleRegistry = [
${articles}
] as const satisfies readonly RegisteredArticle[];
`;

const existingRegistry = await readFile(registryPath, "utf8").catch(() => "");

if (existingRegistry !== registry) {
  await writeFile(registryPath, registry, "utf8");
  console.log(`Generated blog registry with ${entries.length} articles.`);
} else {
  console.log(`Blog registry is current (${entries.length} articles).`);
}
